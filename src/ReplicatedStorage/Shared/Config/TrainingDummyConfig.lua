-- Настройки тренировочных манекенов (режимы поведения).
-- Манекен использует те же боевые состояния и анимации, что и игроки.
--
-- Режимы:
--   Passive  - неподвижная цель: принимает урон, ничего не делает.
--   Blocking - периодически поднимает блок: проверка блока, снижения урона и парирования.
--              Окно парирования открывается в момент поднятия блока (см. Block.ParryWindow
--              в CombatStateConfig), поэтому для проверки парирования бейте сразу после того,
--              как манекен поднял блок. Удар сзади или сбоку блок не учитывает.
--   Aggressive - находит ближайшего игрока, поворачивается к нему и атакует через общую
--              боевую систему (те же область удара, кулдаун, блок и парирование игрока).
--              Манекен не ходит: бьёт только тех, кто подошёл на дистанцию удара.
--              Манекен бьёт кулаками (Unarmed); бить других манекенов он не может.
-- IdleTime / HoldTime - случайная пауза между блоками и длительность блока (сек).
-- Aggressive:
--   DetectionRange - с какого расстояния (studs) манекен замечает игрока и поворачивается к нему;
--   Strength       - сила манекена: урон = BaseDamage + Strength * Scaling оружия;
--   ReactionTime   - сколько секунд игрок должен пробыть в зоне удара до первой атаки
--                    (даёт время отойти или поднять блок);
--   TurnAlpha      - резкость поворота за один шаг, 0..1 (меньше = медленнее);
--   MaxAttackAngle - на какой максимум градусов манекен может быть повёрнут от игрока в момент атаки;
--   TickInterval   - как часто (сек) манекен принимает решения.
-- Манекен поворачивается только в Idle: во время замаха он не следит за игроком.

local TrainingDummyConfig = {}

TrainingDummyConfig.DefaultMode = "Passive"

TrainingDummyConfig.Modes = {
    Passive = {
        DisplayName = "Training Dummy",
    },

    Blocking = {
        DisplayName = "Training Dummy (Blocking)",
        IdleTime = { Min = 1.0, Max = 2.0 },
        HoldTime = { Min = 2.0, Max = 3.5 },
    },

    Aggressive = {
        DisplayName = "Training Dummy (Aggressive)",
        DetectionRange = 25,
        Strength = 10,
        ReactionTime = 0.5,
        TurnAlpha = 0.35,
        MaxAttackAngle = 25,
        TickInterval = 0.1,
    },
}

return TrainingDummyConfig
